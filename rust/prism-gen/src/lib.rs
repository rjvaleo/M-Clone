//! idMLab's TypeScript view of the prism-fx catalogue.
//!
//! The ranges, defaults, choices and panels of the shared effects live in one
//! place, the crate, and reach idMLab only through the file this writes:
//! `src/modular/registry/prismCatalog.generated.ts`. `npm run gen:prism`
//! rewrites it, and the test below fails while the committed file is behind
//! the crate — so a range changed there fails idMLab's checks until the file
//! is regenerated.

use prism_fx::{Category, ParamKind, CATALOG};
use std::fmt::Write;

/// Where the file lives, from the workspace root (`rust/`).
pub const TARGET: &str = "../src/modular/registry/prismCatalog.generated.ts";

fn text(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn number(v: f32) -> String {
    format!("{v}")
}

fn list(items: impl IntoIterator<Item = String>) -> String {
    format!("[{}]", items.into_iter().collect::<Vec<_>>().join(", "))
}

fn category(c: Category) -> &'static str {
    match c {
        Category::Delay => "delay",
        Category::Reverb => "reverb",
        Category::Modulation => "modulation",
        Category::Stereo => "stereo",
        Category::Filter => "filter",
        Category::Spectral => "spectral",
        Category::Pitch => "pitch",
        Category::Distortion => "distortion",
        Category::Dynamics => "dynamics",
        Category::Granular => "granular",
        Category::Utility => "utility",
    }
}

/// The whole file.
pub fn render() -> String {
    let mut out = String::new();
    out.push_str(
        "// Generated by rust/prism-gen from the prism-fx catalogue. Do not edit:\n\
         // run `npm run gen:prism`. A parameter's index is its position in `params`.\n\n\
         import type { PrismEffect } from \"./prismTypes\";\n\n\
         export const PRISM_CATALOG: readonly PrismEffect[] = [\n",
    );
    for entry in CATALOG {
        let d = entry.descriptor;
        let params = d.params.iter().map(|p| {
            let (kind, choices) = match p.kind {
                ParamKind::Continuous => ("continuous", "null".to_string()),
                ParamKind::Int => ("int", "null".to_string()),
                ParamKind::Toggle => ("toggle", "null".to_string()),
                ParamKind::Choice(labels) => ("choice", list(labels.iter().map(|l| text(l)))),
            };
            let when = match p.when {
                Some((key, value)) => format!("{{ key: {}, value: {} }}", text(key), number(value)),
                None => "null".to_string(),
            };
            format!(
                "      {{ key: {}, label: {}, min: {}, max: {}, default: {}, log: {}, unit: {}, kind: \"{kind}\", choices: {choices}, when: {when} }}",
                text(p.key), text(p.label), number(p.min), number(p.max), number(p.default), p.log, text(p.unit),
            )
        });
        let groups = d.panel.groups.iter().map(|g| {
            format!("{{ label: {}, keys: {} }}", text(g.label), list(g.keys.iter().map(|k| text(k))))
        });
        let sound = match d.sound {
            Some(s) => format!("{{ key: {}, label: {} }}", text(s.key), text(s.label)),
            None => "null".to_string(),
        };
        let _ = writeln!(
            out,
            "  {{\n    id: {}, code: {}, label: {}, category: \"{}\", source: {},\n    sound: {sound},\n    params: [\n{}\n    ],\n    groups: {},\n    primary: {},\n  }},",
            text(d.id),
            d.code,
            text(d.label),
            category(d.category),
            text(d.source),
            params.collect::<Vec<_>>().join(",\n"),
            list(groups),
            list(d.panel.primary.iter().map(|k| text(k))),
        );
    }
    out.push_str("];\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_committed_catalogue_is_current() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join(TARGET);
        let committed = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            committed == render(),
            "{} is behind the prism-fx catalogue: run `npm run gen:prism`",
            path.display()
        );
    }

    #[test]
    fn every_effect_is_written() {
        let rendered = render();
        for entry in CATALOG {
            assert!(rendered.contains(&format!("id: \"{}\"", entry.descriptor.id)), "{}", entry.descriptor.id);
        }
    }
}
